#!/usr/bin/env python3
"""Plot PerfectDou evaluation curves against DouZero from CSV.

Reads the eval CSV generated by `perfectdou_train --eval-every N` or `perfectdou_eval`
and renders WP (Win Rate) and ADP trend curves.

Usage:
  python tools/plot_eval.py --csv ckpt/eval_vs_douzero.csv --out ckpt/eval_curve.png
  python tools/plot_eval.py --csv ckpt/eval_vs_douzero.csv --x minutes
  python tools/plot_eval.py --csv ckpt/eval_vs_douzero.csv --watch 30
"""
from __future__ import annotations

import argparse
import csv
import sys
import time
from pathlib import Path

try:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    import numpy as np
except ImportError:
    sys.exit("Error: matplotlib and numpy are required. Install with: pip install matplotlib numpy")


def read_eval_csv(csv_path: Path) -> list[dict]:
    if not csv_path.is_file():
        return []
    rows = []
    with csv_path.open("r", encoding="utf-8", newline="") as f:
        reader = csv.DictReader(f)
        for r in reader:
            rows.append(r)
    return rows


def parse_rows(rows: list[dict], x_col: str = "update") -> list[dict]:
    parsed = []
    for r in rows:
        try:
            x_val = float(r.get(x_col, r.get("update", 0)))
            wp = float(r.get("wp", 0))
            adp = float(r.get("adp", 0))
            wp_l = float(r.get("wp_landlord", wp))
            adp_l = float(r.get("adp_landlord", adp))
            wp_p = float(r.get("wp_peasant", wp))
            adp_p = float(r.get("adp_peasant", adp))
            games = int(r.get("games", 0))
            parsed.append({
                "x": x_val,
                "wp": wp,
                "adp": adp,
                "wp_l": wp_l,
                "adp_l": adp_l,
                "wp_p": wp_p,
                "adp_p": adp_p,
                "games": games,
            })
        except (ValueError, TypeError):
            continue
    parsed.sort(key=lambda item: item["x"])
    return parsed


def compute_smooth(y: np.ndarray, alpha: float = 0.15) -> tuple[np.ndarray, np.ndarray]:
    """Compute Exponential Moving Average (EMA) and rolling standard deviation."""
    n = len(y)
    if n == 0:
        return y.copy(), np.zeros_like(y)
    smoothed = np.empty(n, dtype=float)
    smoothed[0] = y[0]
    for i in range(1, n):
        smoothed[i] = alpha * y[i] + (1.0 - alpha) * smoothed[i - 1]

    # Rolling standard deviation over a small window to reflect eval variance
    win = max(3, min(15, n // 4))
    stds = np.empty(n, dtype=float)
    for i in range(n):
        i_start = max(0, i - win + 1)
        sub = y[i_start : i + 1]
        stds[i] = np.std(sub) if len(sub) > 1 else 0.0
    return smoothed, stds


def plot_single(parsed: list[dict], out_png: Path, x_col: str = "update") -> bool:
    if not parsed:
        return False
    x = np.array([p["x"] for p in parsed], dtype=float)
    wp = np.array([p["wp"] for p in parsed], dtype=float)
    adp = np.array([p["adp"] for p in parsed], dtype=float)
    wp_l = np.array([p["wp_l"] for p in parsed], dtype=float)
    adp_l = np.array([p["adp_l"] for p in parsed], dtype=float)
    wp_p = np.array([p["wp_p"] for p in parsed], dtype=float)
    adp_p = np.array([p["adp_p"] for p in parsed], dtype=float)

    fig, axes = plt.subplots(2, 1, figsize=(11, 8), sharex=True)

    # Subplot 1: Win Rate (WP)
    ax1 = axes[0]
    ax1.axhline(0.5, color="gray", linestyle=":", linewidth=1, label="50% baseline")

    # Raw scatter points and light lines for individual runs
    ax1.plot(x, wp_l, "^--", color="#ff7f0e", linewidth=1.0, markersize=3.5, alpha=0.45, label="Landlord WP")
    ax1.plot(x, wp_p, "v--", color="#2ca02c", linewidth=1.0, markersize=3.5, alpha=0.45, label="Peasant WP")
    ax1.plot(x, wp, "o-", color="#1f77b4", linewidth=1.0, markersize=3.5, alpha=0.35, label="Overall WP (Raw)")

    # Smoothed robust trend line + confidence envelope
    if len(x) >= 3:
        smooth_wp, std_wp = compute_smooth(wp, alpha=0.15)
        ax1.plot(x, smooth_wp, "-", color="#d62728", linewidth=2.4, label="Overall WP (Smoothed Trend)")
        ax1.fill_between(x, smooth_wp - std_wp, smooth_wp + std_wp, color="#d62728", alpha=0.15, label="WP ±1σ Band")
        # Also smooth Landlord & Peasant if plenty of data
        if len(x) >= 10:
            smooth_l, _ = compute_smooth(wp_l, alpha=0.15)
            smooth_p, _ = compute_smooth(wp_p, alpha=0.15)
            ax1.plot(x, smooth_l, "-", color="#ff7f0e", linewidth=1.6, alpha=0.9, label="Landlord Trend")
            ax1.plot(x, smooth_p, "-", color="#2ca02c", linewidth=1.6, alpha=0.9, label="Peasant Trend")

    ax1.set_ylabel("Win Rate (WP)", fontsize=11)
    ax1.set_title("PerfectDou vs DouZero Evaluation Progress", fontsize=13, fontweight="bold")
    ax1.grid(True, linestyle="--", alpha=0.4)
    ax1.legend(loc="best", framealpha=0.9, ncol=2)

    # Subplot 2: ADP (Average Difference Points)
    ax2 = axes[1]
    ax2.axhline(0.0, color="gray", linestyle=":", linewidth=1, label="0.0 baseline")

    ax2.plot(x, adp_l, "^--", color="#e377c2", linewidth=1.0, markersize=3.5, alpha=0.45, label="Landlord ADP")
    ax2.plot(x, adp_p, "v--", color="#17becf", linewidth=1.0, markersize=3.5, alpha=0.45, label="Peasant ADP")
    ax2.plot(x, adp, "s-", color="#9467bd", linewidth=1.0, markersize=3.5, alpha=0.35, label="Overall ADP (Raw)")

    if len(x) >= 3:
        smooth_adp, std_adp = compute_smooth(adp, alpha=0.15)
        ax2.plot(x, smooth_adp, "-", color="#d62728", linewidth=2.4, label="Overall ADP (Smoothed Trend)")
        ax2.fill_between(x, smooth_adp - std_adp, smooth_adp + std_adp, color="#d62728", alpha=0.15, label="ADP ±1σ Band")
        if len(x) >= 10:
            smooth_al, _ = compute_smooth(adp_l, alpha=0.15)
            smooth_ap, _ = compute_smooth(adp_p, alpha=0.15)
            ax2.plot(x, smooth_al, "-", color="#e377c2", linewidth=1.6, alpha=0.9, label="Landlord ADP Trend")
            ax2.plot(x, smooth_ap, "-", color="#17becf", linewidth=1.6, alpha=0.9, label="Peasant ADP Trend")

    x_label = "Training Update" if x_col == "update" else "Elapsed Time (minutes)"
    ax2.set_xlabel(x_label, fontsize=11)
    ax2.set_ylabel("ADP (Reward / Game)", fontsize=11)
    ax2.grid(True, linestyle="--", alpha=0.4)
    ax2.legend(loc="best", framealpha=0.9, ncol=2)

    fig.tight_layout()
    out_png.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_png, dpi=140)
    plt.close(fig)
    return True


def plot_comparison(datasets: list[tuple[str, list[dict]]], out_png: Path, x_col: str = "update") -> bool:
    valid_data = [(label, parse_rows(rows, x_col)) for label, rows in datasets]
    valid_data = [(label, p) for label, p in valid_data if len(p) > 0]
    if not valid_data:
        return False
    if len(valid_data) == 1:
        return plot_single(valid_data[0][1], out_png, x_col)

    colors = ["#1f77b4", "#ff7f0e", "#2ca02c", "#d62728", "#9467bd", "#8c564b", "#e377c2", "#7f7f7f"]
    markers = ["o", "s", "^", "v", "D", "P", "*", "X"]

    fig, axes = plt.subplots(2, 1, figsize=(11, 8), sharex=True)
    ax1, ax2 = axes[0], axes[1]

    ax1.axhline(0.5, color="gray", linestyle=":", linewidth=1, label="50% baseline")
    ax2.axhline(0.0, color="gray", linestyle=":", linewidth=1, label="0.0 baseline")

    for i, (label, parsed) in enumerate(valid_data):
        c = colors[i % len(colors)]
        m = markers[i % len(markers)]
        x = np.array([p["x"] for p in parsed], dtype=float)
        wp = np.array([p["wp"] for p in parsed], dtype=float)
        adp = np.array([p["adp"] for p in parsed], dtype=float)

        ax1.plot(x, wp, marker=m, color=c, linewidth=1.0, markersize=3.5, alpha=0.35, label=f"{label} (Raw)")
        ax2.plot(x, adp, marker=m, color=c, linewidth=1.0, markersize=3.5, alpha=0.35, label=f"{label} (Raw)")

        if len(x) >= 3:
            smooth_wp, std_wp = compute_smooth(wp, alpha=0.15)
            smooth_adp, std_adp = compute_smooth(adp, alpha=0.15)
            ax1.plot(x, smooth_wp, "-", color=c, linewidth=2.2, label=f"{label} (Trend)")
            ax2.plot(x, smooth_adp, "-", color=c, linewidth=2.2, label=f"{label} (Trend)")
            ax1.fill_between(x, smooth_wp - std_wp, smooth_wp + std_wp, color=c, alpha=0.1)
            ax2.fill_between(x, smooth_adp - std_adp, smooth_adp + std_adp, color=c, alpha=0.1)

    ax1.set_ylabel("Win Rate (WP)", fontsize=11)
    ax1.set_title("A/B Experiment Comparison vs DouZero", fontsize=13, fontweight="bold")
    ax1.grid(True, linestyle="--", alpha=0.4)
    ax1.legend(loc="best", framealpha=0.9, ncol=2)

    x_label = "Training Update" if x_col == "update" else "Elapsed Time (minutes)"
    ax2.set_xlabel(x_label, fontsize=11)
    ax2.set_ylabel("ADP (Reward / Game)", fontsize=11)
    ax2.grid(True, linestyle="--", alpha=0.4)
    ax2.legend(loc="best", framealpha=0.9, ncol=2)

    fig.tight_layout()
    out_png.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_png, dpi=140)
    plt.close(fig)
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description="Plot PerfectDou vs DouZero evaluation curves (single or A/B comparison).")
    parser.add_argument("--csv", nargs="+", default=["ckpt/eval_vs_douzero.csv"], help="One or more eval CSV paths")
    parser.add_argument("--labels", nargs="+", default=None, help="Labels for each CSV in A/B comparison")
    parser.add_argument("--out", default="", help="Path to output PNG image (default: <csv_dir>/eval_curve.png)")
    parser.add_argument("--x", choices=["update", "minutes"], default="update", help="X-axis column")
    parser.add_argument("--watch", type=int, default=0, help="Watch interval in seconds (0 = run once)")
    args = parser.parse_args()

    csv_paths = [Path(p) for p in args.csv]
    out_png = Path(args.out) if args.out else csv_paths[0].parent / "eval_curve.png"

    labels = args.labels
    if labels is None or len(labels) != len(csv_paths):
        labels = [p.parent.name if p.parent.name else p.stem for p in csv_paths]

    def render() -> bool:
        datasets = []
        for label, p in zip(labels, csv_paths):
            if p.is_file():
                datasets.append((label, read_eval_csv(p)))
        if not datasets:
            return False
        return plot_comparison(datasets, out_png, args.x)

    if args.watch > 0:
        print(f"[EvalPlotter] Monitoring {len(csv_paths)} CSV(s) every {args.watch}s -> {out_png}", flush=True)
        if any(p.is_file() for p in csv_paths):
            render()
        else:
            print(f"[EvalPlotter] Waiting for first eval data in {csv_paths[0]}...", flush=True)
        last_mtimes = {}
        while True:
            changed = False
            for p in csv_paths:
                if p.is_file():
                    mt = p.stat().st_mtime
                    if last_mtimes.get(str(p)) != mt:
                        changed = True
                        last_mtimes[str(p)] = mt
            if changed:
                if render():
                    print(f"[EvalPlotter] [{time.strftime('%H:%M:%S')}] Updated {out_png}", flush=True)
            time.sleep(args.watch)
    else:
        if render():
            print(f"Successfully generated plot at {out_png}")
            return 0
        else:
            print("Failed to generate plot: no valid CSV data found.")
            return 1


if __name__ == "__main__":
    sys.exit(main())
